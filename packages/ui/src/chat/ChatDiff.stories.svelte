<script module lang="ts">
	import { defineMeta } from '@storybook/addon-svelte-csf';
	import { expect, waitFor } from 'storybook/test';
	import ChatDiff from './ChatDiff.svelte';
	import { diffFiles, unusualDiffFiles } from './fixtures.ts';

	const { Story } = defineMeta({
		title: 'Chat/Diff',
		component: ChatDiff,
		tags: ['!autodocs'],
		args: { files: diffFiles }
	});
</script>

<Story
	name="Changes"
	play={async ({ canvas, userEvent }) => {
		const header = canvas.getByRole('button', { name: /src\/lib\/\s*members\.ts/, expanded: true });
		await expect(canvas.getAllByText(/allMembers/).length).toBeGreaterThan(0);
		await userEvent.click(header);
		await expect(header).toHaveAttribute('aria-expanded', 'false');
	}}
/>

<Story
	name="Binary, large and deleted"
	args={{ files: unusualDiffFiles }}
	play={async ({ canvas, userEvent }) => {
		await expect(canvas.getByText('Binary file')).toBeVisible();
		await userEvent.click(canvas.getByRole('button', { name: 'Show' }));
		await waitFor(() => expect(canvas.getByText('// generated by drizzle-kit')).toBeVisible());
	}}
/>

<Story name="Narrow" asChild>
	<div style="inline-size: 22rem">
		<ChatDiff files={diffFiles} />
	</div>
</Story>
